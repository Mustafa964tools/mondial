export function translateTextKu(text: string | undefined | null): string {
  if (!text) return '';
  let result = text.trim();
  
  // Try exact lookup first
  if (TEAM_TRANSLATIONS_KU[result]) return TEAM_TRANSLATIONS_KU[result];
  if (PHRASE_TRANSLATIONS[result]) return PHRASE_TRANSLATIONS[result];
  if (PLAYER_TRANSLATIONS[result]) return PLAYER_TRANSLATIONS[result];

  // Replace known team names
  for (const [eng, ku] of Object.entries(TEAM_TRANSLATIONS_KU)) {
    if (eng.length <= 2) continue;
    if (result.includes(eng)) {
      result = result.split(eng).join(ku);
    }
  }

  // Replace known names
  for (const [eng, ku] of Object.entries(PLAYER_TRANSLATIONS)) {
    if (eng.length <= 2) continue;
    if (result.includes(eng)) {
      result = result.split(eng).join(ku);
    }
  }

  // Replace known phrases
  for (const [eng, ku] of Object.entries(PHRASE_TRANSLATIONS)) {
    if (eng.length <= 2) continue;
    if (result.includes(eng)) {
      result = result.split(eng).join(ku);
    }
  }

  // Common patterns
  if (result.toLowerCase().includes('yellow card')) {
    result = result.replace(/yellow card/gi, 'کارتی زەرد');
  }
  if (result.toLowerCase().includes('red card')) {
    result = result.replace(/red card/gi, 'کارتی سوور');
  }
  if (result.toLowerCase().includes('own goal')) {
    result = result.replace(/own goal/gi, 'گۆڵی خۆیی');
  }

  return result;
}
